"""Validate data/builds/*.json against heroes.json + gear.json and write data/builds.js.

Usage (from the site dir): python3 -I tools/merge_builds.py
Fails loudly on: wrong tier budgets, points over maxPoints, talents the class/subclass/ability
does not own, unknown gear refs, missing provenance tags, or missing quotes.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
H = json.loads((ROOT / "data/heroes.json").read_text())
G = json.loads((ROOT / "data/gear.json").read_text())
BUDGET = {1: 5, 2: 6, 3: 8, 4: 10}
TAGS = {"코드 계산", "설명문 기준", "추정"}
TALENT = H["talents"]
SUB = {s["id"]: s for s in H["subclasses"]}
ABIL = {a["id"]: a for a in H["abilities"]}
GEAR_IDS = {w["id"] for w in G["meleeWeapons"]} | {a["id"] for a in G["armor"]["items"]} \
    | {e["id"] for e in G["enchantments"]["items"]} | {e["id"] for e in G["glyphs"]["items"]}
SHARED_T4 = {"HEROIC_ENERGY"}


def check_tag(obj, where):
    assert obj.get("tag") in TAGS, f"{where}: bad tag {obj.get('tag')!r}"
    if obj["tag"] in ("코드 계산", "설명문 기준"):
        assert obj.get("quote") or any(ch.isdigit() for ch in obj.get("why", "")), f"{where}: needs a quoted number"


out, errors = {}, []
for cls in H["classes"]:
    cid = cls["id"]
    path = ROOT / f"data/builds/{cid}.json"
    if not path.exists():
        errors.append(f"missing {path.name}")
        continue
    b = json.loads(path.read_text())
    try:
        assert b["class"] == cid
        assert b.get("summaryTag") in TAGS, f"{cid}: summaryTag"
        assert b["subclassVerdict"]["pick"] in cls["subclasses"] + [None], f"{cid}: verdict pick"
        check_tag(b["subclassVerdict"], f"{cid} verdict")
        assert {x["subclass"] for x in b["builds"]} == set(cls["subclasses"]), f"{cid}: one build per subclass"
        for build in b["builds"]:
            where = f"{cid}/{build['subclass']}"
            ab = build["armorAbility"]["id"].upper()
            assert ab in ABIL and cid in ABIL[ab]["classes"], f"{where}: ability {ab}"
            check_tag(build["armorAbility"], where + " ability")
            owned = {1: set(cls["talents"]["t1"]), 2: set(cls["talents"]["t2"]),
                     3: set(cls["talents"]["t3"]) | set(SUB[build["subclass"]]["talents"]),
                     4: set(ABIL[ab]["talents"]) | SHARED_T4}
            spent = {1: 0, 2: 0, 3: 0, 4: 0}
            for t in build["talents"]:
                info = TALENT[t["id"]]
                tier = info["tier"]
                assert t["id"] in owned[tier], f"{where}: {t['id']} not owned at tier {tier}"
                assert 1 <= t["points"] <= info["maxPoints"], f"{where}: {t['id']} points {t['points']}>{info['maxPoints']}"
                check_tag(t, f"{where}/{t['id']}")
                spent[tier] += t["points"]
            assert spent == BUDGET, f"{where}: budget {spent} != {BUDGET}"
            per_tier = {}
            for x in build.get("bonus", []):
                per_tier[x["tier"]] = per_tier.get(x["tier"], 0) + x["points"]
                assert x["id"] in owned[x["tier"]], f"{where}: bonus {x['id']}"
                assert x["tag"] in TAGS
            assert all(v <= 2 for v in per_tier.values()), f"{where}: bonus > 2 in a tier"
            for gi in build["gear"]:
                assert gi.get("ref") in GEAR_IDS or gi.get("name"), f"{where}: gear {gi}"
                check_tag(gi, f"{where}/gear")
            assert build.get("playstyleTag") in TAGS
    except (AssertionError, KeyError) as e:
        errors.append(f"{cid}: {e!r}")
        continue
    out[cid] = b

if errors:
    raise SystemExit("INVALID:\n" + "\n".join(errors))
(ROOT / "data/builds.js").write_text("// Generated by tools/merge_builds.py from data/builds/*.json\n"
                                     f"window.SPD_BUILDS = {json.dumps(out, ensure_ascii=False)};\n")
print(f"ok: {len(out)} classes, {sum(len(b['builds']) for b in out.values())} builds")
